// cards.js — Rendering TV shared cards and .ics calendar generation
// All DOM construction uses textContent to prevent XSS. Untrusted strings are never parsed as HTML.

function isValidHttpsUrl(string) {
  if (!string || typeof string !== 'string') return false;
  try {
    const url = new URL(string);
    return url.protocol === 'https:';
  } catch (_) {
    return false;
  }
}

function formatIsoForIcs(date) {
  const pad = (n) => String(n).padStart(2, '0');
  return (
    date.getUTCFullYear() +
    pad(date.getUTCMonth() + 1) +
    pad(date.getUTCDate()) +
    'T' +
    pad(date.getUTCHours()) +
    pad(date.getUTCMinutes()) +
    pad(date.getUTCSeconds()) +
    'Z'
  );
}

export function generateIcs(title, startTimeIso, repeat) {
  let startDate = new Date(startTimeIso);
  if (isNaN(startDate.getTime())) {
    startDate = new Date();
  }
  const endDate = new Date(startDate.getTime() + 30 * 60 * 1000); // 30 min default duration
  const now = new Date();
  const uid = 'sx-' + Date.now() + '-' + Math.random().toString(36).substring(2, 9) + '@studiox.link';

  const lines = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//StudioX//StudioX Link//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    'BEGIN:VEVENT',
    'UID:' + uid,
    'DTSTAMP:' + formatIsoForIcs(now),
    'DTSTART:' + formatIsoForIcs(startDate),
    'DTEND:' + formatIsoForIcs(endDate),
    'SUMMARY:' + (title || 'StudioX Reminder').replace(/[\r\n]+/g, ' '),
    'DESCRIPTION:Generated by StudioX Link'
  ];

  if (repeat === 'daily') {
    lines.push('RRULE:FREQ=DAILY');
  } else if (repeat === 'weekly') {
    lines.push('RRULE:FREQ=WEEKLY');
  }

  lines.push('END:VEVENT', 'END:VCALENDAR');
  return lines.join('\r\n');
}

export function downloadIcs(filename, icsContent) {
  const blob = new Blob([icsContent], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename || 'reminder.ics';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function renderCard(message) {
  const card = message.card;
  if (!card || !card.type) return null;

  const cardEl = document.createElement('article');
  cardEl.className = 'tv-card card-' + card.type;
  cardEl.setAttribute('role', 'region');
  cardEl.setAttribute('aria-label', (card.title || 'Card from TV'));

  // Header: mono FROM TV · <time> + Copy button
  const header = document.createElement('header');
  header.className = 'card-header';

  const headerTag = document.createElement('span');
  headerTag.className = 'card-tag mono';
  const msgTime = message.at ? new Date(message.at).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }) : '';
  headerTag.textContent = msgTime ? `FROM TV · ${msgTime}` : 'FROM TV';
  header.appendChild(headerTag);

  const copyBtn = document.createElement('button');
  copyBtn.type = 'button';
  copyBtn.className = 'card-copy-btn mono';
  copyBtn.setAttribute('aria-label', 'Copy card text to clipboard');
  copyBtn.textContent = 'COPY';
  header.appendChild(copyBtn);
  cardEl.appendChild(header);

  // Card Title
  if (card.title) {
    const titleEl = document.createElement('h3');
    titleEl.className = 'card-title';
    titleEl.textContent = card.title;
    cardEl.appendChild(titleEl);
  }

  // Plain-text representation for Copy action
  let plainTextLines = [card.title || 'StudioX Card'];

  // Card Body by type
  if (card.type === 'checklist') {
    const listEl = document.createElement('ul');
    listEl.className = 'card-checklist';

    const storageKey = 'sx_chk_' + message.id;
    let savedState = {};
    try {
      savedState = JSON.parse(localStorage.getItem(storageKey) || '{}');
    } catch (_) {
      savedState = {};
    }

    let hasTimedItems = false;
    const items = Array.isArray(card.items) ? card.items : [];

    items.forEach((item, index) => {
      const li = document.createElement('li');
      li.className = 'checklist-item';

      const label = document.createElement('label');
      label.className = 'checklist-label';

      const checkbox = document.createElement('input');
      checkbox.type = 'checkbox';
      checkbox.className = 'checklist-checkbox';
      checkbox.checked = !!savedState[index];

      const itemText = typeof item === 'string' ? item : (item.text || '');
      const itemTime = item && item.time ? item.time : '';
      if (itemTime) hasTimedItems = true;

      plainTextLines.push(`[${checkbox.checked ? 'x' : ' '}] ${itemText}${itemTime ? ' (' + itemTime + ')' : ''}`);

      const contentSpan = document.createElement('span');
      contentSpan.className = 'checklist-text' + (checkbox.checked ? ' is-checked' : '');
      contentSpan.textContent = itemText;

      checkbox.addEventListener('change', () => {
        savedState[index] = checkbox.checked;
        try {
          localStorage.setItem(storageKey, JSON.stringify(savedState));
        } catch (_) {}
        if (checkbox.checked) {
          contentSpan.classList.add('is-checked');
        } else {
          contentSpan.classList.remove('is-checked');
        }
      });

      label.appendChild(checkbox);
      label.appendChild(contentSpan);

      if (itemTime) {
        const timeBadge = document.createElement('span');
        timeBadge.className = 'checklist-time mono';
        timeBadge.textContent = itemTime;
        label.appendChild(timeBadge);
      }

      li.appendChild(label);
      listEl.appendChild(li);
    });

    cardEl.appendChild(listEl);

    // "Add reminder" button if card has times
    if (hasTimedItems || card.hasTimes) {
      const reminderActionWrap = document.createElement('div');
      reminderActionWrap.className = 'card-actions';

      const addReminderBtn = document.createElement('button');
      addReminderBtn.type = 'button';
      addReminderBtn.className = 'card-action-btn mono';
      addReminderBtn.textContent = 'ADD REMINDER';
      addReminderBtn.addEventListener('click', () => {
        const ics = generateIcs(card.title || 'StudioX Protocol Checklist', new Date().toISOString(), 'daily');
        downloadIcs('protocol-routine.ics', ics);
      });
      reminderActionWrap.appendChild(addReminderBtn);
      cardEl.appendChild(reminderActionWrap);
    }
  } else if (card.type === 'list') {
    const listEl = document.createElement('div');
    listEl.className = 'card-keyval-list';

    const items = Array.isArray(card.items) ? card.items : [];
    items.forEach((item) => {
      const row = document.createElement('div');
      row.className = 'card-keyval-row';

      const nameEl = document.createElement('div');
      nameEl.className = 'card-row-name mono';
      nameEl.textContent = item.name || '';

      const detailEl = document.createElement('div');
      detailEl.className = 'card-row-detail';
      detailEl.textContent = item.detail || '';

      plainTextLines.push(`${item.name || ''}: ${item.detail || ''}`);

      row.appendChild(nameEl);
      row.appendChild(detailEl);
      listEl.appendChild(row);
    });

    cardEl.appendChild(listEl);

    // Sources footer if present
    if (Array.isArray(card.sources) && card.sources.length > 0) {
      const sourcesEl = renderSourcesList(card.sources);
      if (sourcesEl) {
        cardEl.appendChild(sourcesEl);
        plainTextLines.push('SOURCES:');
        card.sources.forEach((s) => {
          if (s && s.url) plainTextLines.push(`- ${s.title || s.url}: ${s.url}`);
        });
      }
    }
  } else if (card.type === 'person') {
    const person = card.person || {};
    const wrap = document.createElement('div');
    wrap.className = 'card-person';

    if (person.imageUrl && isValidHttpsUrl(person.imageUrl)) {
      const img = document.createElement('img');
      img.className = 'person-portrait';
      img.src = person.imageUrl;
      img.alt = person.name || 'Portrait';
      img.loading = 'lazy';
      wrap.appendChild(img);
    }

    const info = document.createElement('div');
    info.className = 'person-info';

    if (person.name) {
      const name = document.createElement('h4');
      name.className = 'person-name';
      name.textContent = person.name;
      info.appendChild(name);
      plainTextLines.push(person.name);
    }

    if (person.role) {
      const role = document.createElement('p');
      role.className = 'person-role mono';
      role.textContent = person.role;
      info.appendChild(role);
      plainTextLines.push(person.role);
    }

    if (Array.isArray(person.facts) && person.facts.length > 0) {
      const factsList = document.createElement('ul');
      factsList.className = 'person-facts';
      person.facts.slice(0, 3).forEach((fact) => {
        const factLi = document.createElement('li');
        factLi.textContent = fact;
        factsList.appendChild(factLi);
        plainTextLines.push(`• ${fact}`);
      });
      info.appendChild(factsList);
    }

    if (person.credit) {
      const credit = document.createElement('p');
      credit.className = 'person-credit mono';
      credit.textContent = person.credit;
      info.appendChild(credit);
    }

    wrap.appendChild(info);
    cardEl.appendChild(wrap);
  } else if (card.type === 'link') {
    const linkWrap = document.createElement('div');
    linkWrap.className = 'card-link-wrap';

    const url = card.url || '';
    if (isValidHttpsUrl(url)) {
      let hostname = '';
      try {
        hostname = new URL(url).hostname;
      } catch (_) {}

      const domainEl = document.createElement('span');
      domainEl.className = 'link-domain mono';
      domainEl.textContent = hostname.toUpperCase();

      const anchor = document.createElement('a');
      anchor.className = 'card-external-link';
      anchor.href = url;
      anchor.target = '_blank';
      anchor.rel = 'noopener noreferrer';
      anchor.textContent = card.title || url;

      linkWrap.appendChild(domainEl);
      linkWrap.appendChild(anchor);
      plainTextLines.push(`${card.title || 'Link'}: ${url}`);
    }
    cardEl.appendChild(linkWrap);
  } else if (card.type === 'reminder') {
    const reminder = card.reminder || {};
    const wrap = document.createElement('div');
    wrap.className = 'card-reminder-wrap';

    const remTitle = reminder.title || card.title || 'Reminder';
    const remTimeStr = reminder.start ? new Date(reminder.start).toLocaleString() : '';
    const remRepeat = reminder.repeat ? reminder.repeat.toUpperCase() : '';

    const meta = document.createElement('div');
    meta.className = 'reminder-meta mono';
    meta.textContent = `${remTimeStr}${remRepeat ? ' · ' + remRepeat : ''}`;

    plainTextLines.push(`${remTitle} — ${remTimeStr} ${remRepeat}`);

    const addCalBtn = document.createElement('button');
    addCalBtn.type = 'button';
    addCalBtn.className = 'card-action-btn mono';
    addCalBtn.textContent = 'ADD TO CALENDAR';
    addCalBtn.addEventListener('click', () => {
      const ics = generateIcs(remTitle, reminder.start || new Date().toISOString(), reminder.repeat);
      downloadIcs('reminder.ics', ics);
    });

    wrap.appendChild(meta);
    wrap.appendChild(addCalBtn);
    cardEl.appendChild(wrap);
  }

  // Copy button handler
  copyBtn.addEventListener('click', async () => {
    const fullText = plainTextLines.filter(Boolean).join('\n');
    try {
      if (navigator.clipboard && navigator.clipboard.writeText) {
        await navigator.clipboard.writeText(fullText);
      } else {
        const textarea = document.createElement('textarea');
        textarea.value = fullText;
        textarea.style.position = 'fixed';
        textarea.style.opacity = '0';
        document.body.appendChild(textarea);
        textarea.select();
        document.execCommand('copy');
        document.body.removeChild(textarea);
      }
      copyBtn.textContent = 'COPIED';
      setTimeout(() => {
        copyBtn.textContent = 'COPY';
      }, 1500);
    } catch (e) {
      copyBtn.textContent = 'FAILED';
      setTimeout(() => {
        copyBtn.textContent = 'COPY';
      }, 1500);
    }
  });

  return cardEl;
}

export function renderSourcesList(sources) {
  if (!Array.isArray(sources) || sources.length === 0) return null;

  const validSources = sources.filter((s) => s && isValidHttpsUrl(s.url));
  if (validSources.length === 0) return null;

  const container = document.createElement('div');
  container.className = 'sources-container';

  const label = document.createElement('div');
  label.className = 'sources-label mono';
  label.textContent = 'SOURCES';
  container.appendChild(label);

  const list = document.createElement('ul');
  list.className = 'sources-list';

  validSources.forEach((source) => {
    const li = document.createElement('li');
    li.className = 'source-item';

    const a = document.createElement('a');
    a.className = 'source-link';
    a.href = source.url;
    a.target = '_blank';
    a.rel = 'noopener noreferrer';
    a.textContent = source.title || source.url;

    li.appendChild(a);
    list.appendChild(li);
  });

  container.appendChild(list);
  return container;
}
