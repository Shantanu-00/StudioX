#!/usr/bin/env python3
"""Seed the demo packages (the two demo episodes) and the cameo examples.

  seed_demo.py local [ID..]     run backend/agents/run_local.py per transcript, validate, keep if valid
  seed_demo.py cloud [ID..]     OWNER, admin creds: upload transcripts, run StudioX-EpisodeAnalysis, pull latest.json
  seed_demo.py index            regenerate src/analysis/packages/index.ts from the JSON files present
  seed_demo.py validate FILE..  validate package files

ID defaults to the two demo episodes; `all` adds the cameo examples (transcripts StudioX wrote,
packaged with `example: true` and a `title`). Pinned Map questions (PINNED) go to run_local as
--question and to the cloud execution input as `pinnedQuestions`.

Local needs only Bedrock access. Cloud needs S3 and Step Functions (the restricted `claude-code`
profile cannot). Environment for cloud: AWS_PROFILE, AWS_REGION (default us-east-1),
STACK (default StudioXCore).
"""
import json, os, subprocess, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
IDS = ["science-ep42", "crime-case104"]
CAMEOS = ["cameo-finance", "cameo-tech", "cameo-history"]
# Questions pinned on the Map for the demo video (the crime beat asks this at about 0:12).
PINNED = {"crime-case104": [{"t": 12, "question": "Does the ping break his alibi?"}]}
PKG = ROOT / "src/analysis/packages"
TRANS = ROOT / "backend/data/transcripts"
RUN_LOCAL = ROOT / "backend/agents/run_local.py"
TYPES = {"dossier", "timeline", "relation_graph", "entity_list", "protocol", "technique", "claim"}


def validate(pkg, media_id=None):
    """Return a list of problems. Uses A's schema.py when present, else a structural check."""
    sys.path.insert(0, str(ROOT / "backend/shared/python"))
    try:
        from studiox_core import schema  # type: ignore
        fn = getattr(schema, "validate_package", None)
        if fn:
            r = fn(pkg, media_id)
            if r in (None, True, []):
                return []
            return list(r) if isinstance(r, (list, tuple)) else [str(r)]
    except ImportError:
        pass
    p = []
    for k in ("mediaId", "segments", "moments", "widgets", "transcript"):
        if k not in pkg:
            p.append(f"missing {k}")
    if pkg.get("provenance") != "pipeline":
        p.append("provenance != pipeline")
    if media_id and pkg.get("mediaId") != media_id:
        p.append("mediaId mismatch")
    ids = set()
    for w in pkg.get("widgets", []):
        if w.get("type") not in TYPES:
            p.append(f"widget type {w.get('type')}")
        if not w.get("id") or w["id"] in ids:
            p.append(f"widget id {w.get('id')}")
        ids.add(w.get("id"))
        ev = w.get("evidence")
        if not ev or not all(isinstance(e.get("t0"), (int, float)) and e.get("t1", -1) >= e.get("t0", 0) for e in ev):
            p.append(f"evidence {w.get('id')}")
    for a in pkg.get("answers", []):
        for s in a.get("sources", []):
            if not str(s.get("url", "")).startswith("https://"):
                p.append("non-https source")
    return p


def write_index():
    have = [i for i in IDS + CAMEOS if (PKG / f"{i}.json").exists()]
    lines = ["// Generated by backend/scripts/seed_demo.py index. Do not edit by hand.",
             "// Bundled episode packages (EpisodeAnalysis + pipeline fields), keyed by media id.",
             "// Static requires only, so Metro can resolve them; ids without a file are absent.",
             "export const BUNDLED: Record<string, unknown> = {"]
    lines += [f"  '{i}': require('./{i}.json')," for i in have]
    lines += ["};", ""]
    (PKG / "index.ts").write_text("\n".join(lines))
    print("index.ts:", have)


def pick(args):
    if not args:
        return list(IDS)
    if args == ["all"]:
        return IDS + CAMEOS
    bad = [a for a in args if a not in IDS + CAMEOS]
    if bad:
        sys.exit(f"unknown ids {bad}; known: {IDS + CAMEOS}")
    return list(args)


def local_args(i):
    """run_local options for one id: pinned questions, and the example flag for cameos."""
    out = []
    for q in PINNED.get(i, []):
        out += ["--question", f"{q['t']}|{q['question']}"]
    if i in CAMEOS:
        out.append("--example")
    return out


def execution_input(i, bucket):
    inp = {"mediaId": i, "bucket": bucket, "transcriptKey": f"transcripts/{i}.json"}
    if PINNED.get(i):
        inp["pinnedQuestions"] = PINNED[i]
    if i in CAMEOS:
        inp["example"] = True
        title = json.loads((TRANS / f"{i}.json").read_text()).get("title")
        if title:
            inp["title"] = title
    return inp


def local(ids):
    t_wait = 0
    while not RUN_LOCAL.exists():
        if t_wait >= 3600:
            sys.exit("run_local.py never appeared")
        print("waiting for run_local.py ..."); time.sleep(120); t_wait += 120
    ok = True
    for i in ids:
        out = PKG / f"{i}.json"
        tmp = PKG / f".{i}.tmp.json"
        t = time.time()
        r = subprocess.run(["uv", "run", "--python", "3.13", str(RUN_LOCAL), "package", "--transcript",
                            str(TRANS / f"{i}.json"), "--out", str(tmp), "--media-id", i, *local_args(i)])
        dt = time.time() - t
        if r.returncode or not tmp.exists():
            print(f"{i}: run_local failed rc={r.returncode} after {dt:.0f}s"); ok = False; continue
        pkg = json.loads(tmp.read_text())
        probs = validate(pkg, i)
        if probs:
            print(f"{i}: INVALID, not kept ({dt:.0f}s):", probs[:8]); ok = False; tmp.unlink(); Path(str(tmp) + ".run.json").unlink(missing_ok=True); continue
        tmp.replace(out)
        side = Path(str(tmp) + ".run.json")  # run_local's timings/usage/audit sidecar: keep out of the bundle
        if side.exists():
            (ROOT / "backend/data/runs").mkdir(parents=True, exist_ok=True)
            side.replace(ROOT / f"backend/data/runs/{i}.run.json")
        print(f"{i}: kept {out.name} in {dt:.0f}s; widgets={len(pkg['widgets'])} moments={len(pkg['moments'])} "
              f"segments={len(pkg['segments'])} answers={len(pkg.get('answers', []))} funnel={pkg.get('funnel')}")
    write_index()
    return ok


def aws(*a, **kw):
    r = subprocess.run(["aws", *a, "--region", os.environ.get("AWS_REGION", "us-east-1"), "--output", "json"],
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"aws {' '.join(a[:2])} failed: {r.stderr.strip()}")
    return json.loads(r.stdout) if r.stdout.strip() else {}


def cloud(ids):
    stack = os.environ.get("STACK", "StudioXCore")
    outs = {o["OutputKey"]: o["OutputValue"] for o in aws("cloudformation", "describe-stacks", "--stack-name", stack)["Stacks"][0]["Outputs"]}
    bucket = outs["BucketName"]
    sms = [s for s in aws("stepfunctions", "list-state-machines")["stateMachines"] if s["name"] == "StudioX-EpisodeAnalysis"]
    if not sms:
        sys.exit("state machine StudioX-EpisodeAnalysis not found (deploy B's stack first)")
    arn = sms[0]["stateMachineArn"]
    for i in ids:
        subprocess.run(["aws", "s3", "cp", str(TRANS / f"{i}.json"), f"s3://{bucket}/transcripts/{i}.json",
                        "--content-type", "application/json"], check=True)
    runs = {}
    for i in ids:
        name = f"seed-{i}-{int(time.time())}"
        inp = json.dumps(execution_input(i, bucket))
        runs[i] = aws("stepfunctions", "start-execution", "--state-machine-arn", arn, "--name", name, "--input", inp)["executionArn"]
        print(i, "started", runs[i])
    # NOTE: the input shape is a guess until B's state machine is final; adjust here if B changes it.
    deadline = time.time() + 1800
    pending = dict(runs)
    while pending and time.time() < deadline:
        for i, ea in list(pending.items()):
            st = aws("stepfunctions", "describe-execution", "--execution-arn", ea)
            print(i, st["status"])
            if st["status"] != "RUNNING":
                del pending[i]
                if st["status"] != "SUCCEEDED":
                    print(i, "did not succeed:", st.get("error"), st.get("cause"))
        if pending:
            time.sleep(15)
    PKG.mkdir(parents=True, exist_ok=True)
    for i in ids:
        tmp = PKG / f".{i}.tmp.json"
        r = subprocess.run(["aws", "s3", "cp", f"s3://{bucket}/packages/{i}/latest.json", str(tmp)])
        if r.returncode:
            continue
        probs = validate(json.loads(tmp.read_text()), i)
        if probs:
            print(i, "INVALID, not kept:", probs[:8]); tmp.unlink()
        else:
            tmp.replace(PKG / f"{i}.json"); print(i, "kept")
    write_index()


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "local"
    if cmd == "local":
        sys.exit(0 if local(pick(sys.argv[2:])) else 1)
    elif cmd == "cloud":
        cloud(pick(sys.argv[2:]))
    elif cmd == "index":
        write_index()
    elif cmd == "validate":
        bad = 0
        for f in sys.argv[2:]:
            p = validate(json.loads(Path(f).read_text()))
            print(f, "OK" if not p else p); bad += bool(p)
        sys.exit(bad)
    else:
        sys.exit(__doc__)
